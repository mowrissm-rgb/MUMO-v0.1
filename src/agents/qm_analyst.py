"""
MUMO — electronic structure (HOMO / LUMO) via GFN2-xTB.

WHY THIS AND NOT MD
-------------------
Mowriss asked for molecular dynamics inside 10-15 minutes plus HOMO/LUMO in the
report. The MD half is not achievable on this hardware: measured on the free
2-vCPU Space, trajectory MD runs at ~1 ns/day, so ten minutes buys roughly 8
picoseconds — not a simulation anyone can stand behind. HOMO/LUMO is the
opposite: seconds per molecule, and genuinely informative.

WHY xtb, AND WHY IT IS SAFE HERE
--------------------------------
Adding openmm to the shared conda environment segfaulted ProLIF and took the
whole Space down (exit 139, 2026-07-12). The lesson was not "avoid science", it
was "avoid native libraries that share a process with the rest of the stack".

xtb is a COMMAND-LINE EXECUTABLE, not a Python extension module. It is invoked
as a subprocess, its output is parsed as text, and nothing from it is ever
loaded into this interpreter — so it carries none of the ABI risk that openmm
did. The pattern is exactly how MUMO already runs AutoDock Vina.

REFUSING TO GUESS
-----------------
If the output cannot be parsed, this returns an error rather than a plausible
number. A wrong HOMO/LUMO that looks reasonable is far more damaging than a
missing one, because nothing downstream would flag it.
"""

import os
import re
import shutil
import subprocess
import tempfile
import math
import hashlib

# Hartree -> electronvolt, CODATA
EH_TO_EV = 27.211386245988


def xtb_path():
    """Where xtb lives, or "" if it is not installed."""
    return os.environ.get("MUMO_XTB") or shutil.which("xtb") or ""


def xtb_available():
    return bool(xtb_path())


# The feature flag. Off unless the binary is actually present, so a build that
# lacks xtb simply does not offer the feature rather than failing at use time.
QM_AVAILABLE = xtb_available()


def prepare_xyz(smiles, seed=42):
    """SMILES -> optimised 3D geometry as XYZ text.

    xtb needs coordinates, not a graph. RDKit embeds and MMFF-optimises first
    so xtb starts from something sane; a bad starting geometry makes the SCF
    slow to converge or converge somewhere silly.
    """
    from rdkit import Chem
    from rdkit.Chem import AllChem

    mol = Chem.MolFromSmiles((smiles or "").strip())
    if mol is None or not mol.GetNumAtoms():
        raise ValueError(f"Could not read that structure: {smiles!r}")
    mol = Chem.AddHs(mol)
    if AllChem.EmbedMolecule(mol, randomSeed=seed) != 0:
        raise ValueError("Could not generate a 3D conformer for this molecule.")
    if not AllChem.MMFFHasAllMoleculeParams(mol):
        raise ValueError("MMFF parameters unavailable for this chemical structure.")
    if AllChem.MMFFOptimizeMolecule(mol, maxIters=200) != 0:
        raise ValueError("MMFF geometry optimization failed or did not converge.")

    conf = mol.GetConformer()
    lines = [str(mol.GetNumAtoms()), "generated by MUMO"]
    for atom in mol.GetAtoms():
        p = conf.GetAtomPosition(atom.GetIdx())
        if not all(math.isfinite(v) for v in (p.x, p.y, p.z)):
            raise ValueError("Prepared geometry contains non-finite coordinates.")
        lines.append(f"{atom.GetSymbol():<3}{p.x:>14.8f}{p.y:>14.8f}{p.z:>14.8f}")
    return "\n".join(lines) + "\n", mol.GetNumAtoms()


_HOMO = re.compile(r"^\s*\d+\s+[\d.]+\s+(-?[\d.]+)\s+(-?[\d.]+)\s*\(HOMO\)", re.M)
_LUMO = re.compile(r"^\s*\d+\s+(-?[\d.]+)\s+(-?[\d.]+)\s*\(LUMO\)", re.M)
_GAP = re.compile(r"HL-Gap\s+(-?[\d.]+)\s*Eh\s+(-?[\d.]+)\s*eV", re.I)
_DIPOLE = re.compile(r"^\s*full:\s+\S+\s+\S+\s+\S+\s+([\d.]+)", re.M)
_ENERGY = re.compile(r"TOTAL ENERGY\s+(-?[\d.]+)\s*Eh", re.I)


def parse_xtb(text):
    """Pull the electronic properties out of an xtb run.

    Deliberately anchored on xtb's own labels — "(HOMO)", "(LUMO)", "HL-Gap" —
    rather than on line positions, which shift between versions and between
    single-point and optimisation runs.
    """
    out = {}

    m = _HOMO.search(text or "")
    if m:
        out["homo_eh"], out["homo_ev"] = float(m.group(1)), float(m.group(2))
    m = _LUMO.search(text or "")
    if m:
        out["lumo_eh"], out["lumo_ev"] = float(m.group(1)), float(m.group(2))

    m = _GAP.search(text or "")
    if m:
        out["gap_ev"] = float(m.group(2))
        out['gap_eh'] = float(m.group(1))
    elif "homo_ev" in out and "lumo_ev" in out:
        # derive rather than leave it missing, but only from values we parsed
        out["gap_ev"] = round(out["lumo_ev"] - out["homo_ev"], 4)

    m = _DIPOLE.search(text or "")
    if m:
        out["dipole_debye"] = float(m.group(1))
    m = _ENERGY.search(text or "")
    if m:
        out["total_energy_eh"] = float(m.group(1))

    # every occupied/virtual level, for the orbital diagram
    levels = []
    for line in (text or "").splitlines():
        mm = re.match(r"^\s*(\d+)\s+(?:([\d.]+)\s+)?(-?[\d.]+)\s+(-?[\d.]+)\s*(\(HOMO\)|\(LUMO\))?\s*$",
                      line)
        if mm:
            levels.append({
                "index": int(mm.group(1)),
                "occupation": float(mm.group(2)) if mm.group(2) else 0.0,
                "energy_ev": float(mm.group(4)),
                "label": (mm.group(5) or "").strip("()"),
            })
    if levels:
        out["levels"] = levels
    return out


def _electronic_state(smiles, charge=None, unpaired_electrons=None):
    from rdkit import Chem, rdBase
    mol = Chem.MolFromSmiles((smiles or '').strip())
    if mol is None or not mol.GetNumAtoms():
        raise ValueError("A valid nonempty molecular structure is required.")
    if len(Chem.GetMolFrags(mol)) != 1:
        raise ValueError("Select one molecular component; disconnected salts are unsupported.")
    formal = Chem.GetFormalCharge(mol)
    if charge is not None and (type(charge) is not int or charge != formal):
        raise ValueError("Requested charge disagrees with the input structure's formal charge.")
    mol_h = Chem.AddHs(mol)
    electrons = sum(a.GetAtomicNum() for a in mol_h.GetAtoms()) - formal
    radicals = sum(a.GetNumRadicalElectrons() for a in mol.GetAtoms())
    if unpaired_electrons is None:
        if radicals or electrons % 2:
            raise ValueError("Open-shell structure requires an explicit unpaired-electron count.")
        unpaired_electrons = 0
    if (type(unpaired_electrons) is not int or unpaired_electrons < 0
            or unpaired_electrons > electrons or (electrons - unpaired_electrons) % 2):
        raise ValueError("Unpaired-electron count is incompatible with electron parity.")
    if unpaired_electrons > radicals:
        raise ValueError("Requested spin is unsupported by the input radical specification.")
    return {'charge': formal, 'unpaired_electrons': unpaired_electrons,
            'electron_count': electrons, 'radical_electrons': radicals,
            'canonical_smiles': Chem.MolToSmiles(mol), 'rdkit_version': rdBase.rdkitVersion}


def orbitals(smiles, timeout=180, charge=None, unpaired_electrons=None):
    """HOMO, LUMO, gap and dipole for one molecule.

    Never raises: returns {"_error": ...} so a QM failure degrades this one
    panel rather than the analysis around it.
    """
    evidence = {'input_smiles': smiles, 'checks': [], 'settings': {'seed': 42, 'MMFF_max_iterations': 200,
                'gfn': 2, 'calculation': 'single point', 'solvent': 'gas phase', 'timeout_seconds': timeout}}
    def fail(message, status='failed'):
        evidence['checks'].append({'status': status, 'message': message})
        return {'_error': message, 'status': status, 'result_kind': 'prediction', 'evidence': evidence}
    xtb = xtb_path()
    if not xtb:
        return fail("The xtb quantum-chemistry engine is not installed in this build.", 'unavailable')
    try:
        state = _electronic_state(smiles, charge, unpaired_electrons)
        evidence['electronic_state'] = state
        xyz, n_atoms = prepare_xyz(smiles)
        evidence.update(xyz=xyz, xyz_sha256=hashlib.sha256(xyz.encode('ascii')).hexdigest())
        evidence['checks'].append({'status': 'passed', 'message': 'Input electronic state and MMFF convergence checked.'})
    except Exception as e:
        return fail(str(e))

    with tempfile.TemporaryDirectory(prefix="mumo-qm-") as tmp:
        path = os.path.join(tmp, "mol.xyz")
        with open(path, "w", encoding="ascii") as fh:
            fh.write(xyz)
        cmd = [xtb, "mol.xyz", "--gfn", "2", "--sp", "--chrg", str(state['charge']),
               '--uhf', str(state['unpaired_electrons'])]
        evidence['command'] = cmd
        try:
            proc = subprocess.run(cmd, cwd=tmp, capture_output=True, text=True,
                                  timeout=timeout)
        except subprocess.TimeoutExpired as e:
            def decoded(value):
                return value.decode('utf-8', errors='replace') if isinstance(value, bytes) else (value or '')
            evidence.update(stdout=decoded(e.stdout), stderr=decoded(e.stderr))
            return fail(f"xtb did not finish within {timeout}s.")
        except Exception as e:
            return fail(f"Could not run xtb: {type(e).__name__}: {e}")

        text = (proc.stdout or "") + "\n" + (proc.stderr or "")
        evidence.update(stdout=proc.stdout or '', stderr=proc.stderr or '', returncode=proc.returncode)
        version = re.search(r'xtb\s+version\s+([^\s]+)', text, re.I)
        evidence['xtb_version'] = version.group(1) if version else 'unavailable'

    if proc.returncode != 0:
        return fail(f"xtb exited with code {proc.returncode}.")
    if re.search(r'(?:not\s+converged|failed\s+to\s+converge|convergence\s+failed|abnormal\s+termination)', text, re.I):
        return fail("xtb reported a convergence or execution failure.")
    if not re.search(r'normal termination of xtb', text, re.I):
        return fail("xtb normal termination could not be verified.")
    if re.search(r'\b(?:nan|inf(?:inity)?)\b', text, re.I):
        return fail("xtb output contains non-finite numeric markers.")
    try:
        props = parse_xtb(text)
    except (ValueError, OverflowError):
        return fail("xtb output contains invalid numeric values.")
    if "homo_ev" not in props or "lumo_ev" not in props:
        # Refuse to invent numbers. A plausible-looking wrong HOMO/LUMO is
        # worse than none, because nothing downstream would catch it.
        tail = "\n".join(text.strip().splitlines()[-4:])
        return fail("xtb ran but its output could not be parsed for "
                    f"HOMO/LUMO. Last lines: {tail[:200]}")

    numeric = [v for v in props.values() if isinstance(v, (int, float))]
    numeric += [level['energy_ev'] for level in props.get('levels', [])]
    if not all(math.isfinite(v) for v in numeric):
        return fail("xtb output contains non-finite values.")
    if props['gap_ev'] < 0 or abs(props['gap_ev'] - (props['lumo_ev'] - props['homo_ev'])) > 0.02:
        return fail("HOMO/LUMO ordering or gap consistency check failed.")
    if 'gap_eh' in props and abs(props['gap_eh'] * EH_TO_EV - props['gap_ev']) > 0.02:
        return fail("Gap Hartree/eV unit consistency check failed.")
    for name in ('homo', 'lumo'):
        if abs(props[name + '_eh'] * EH_TO_EV - props[name + '_ev']) > 0.02:
            return fail("Orbital Hartree/eV unit consistency check failed.")
    if props.get('dipole_debye', 0) < 0:
        return fail("Dipole magnitude cannot be negative.")

    props["smiles"] = smiles
    props["n_atoms"] = n_atoms
    props.update(state)
    props.update(status='verified', result_kind='prediction', evidence=evidence,
                 units={'homo_ev': 'eV', 'lumo_ev': 'eV', 'gap_ev': 'eV',
                        'total_energy_eh': 'Hartree', 'dipole_debye': 'Debye'})
    evidence['checks'].append({'status': 'passed', 'message': 'Engine completion and orbital unit/gap consistency checked.'})
    props["method"] = "GFN2-xTB semiempirical single point on MMFF-optimized geometry (gas phase)"
    props["interpretation"] = _interpret(props)
    return props


def _interpret(p):
    """Describe computed orbital energies without assigning unsupported outcomes."""
    if p.get("gap_ev") is None:
        return ""
    return (f"GFN2-xTB predicts HOMO {p['homo_ev']:.2f} eV and LUMO "
            f"{p['lumo_ev']:.2f} eV, with an orbital gap of {p['gap_ev']:.2f} eV. "
            "This is a semiempirical single-point prediction for the recorded chemical "
            "state and geometry, not an experimental measurement or an excitation energy. "
            "These orbital energies alone do not establish chemical stability, "
            "metabolic liability, or electron-transfer rates.")
